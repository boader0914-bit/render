"use strict";

const assert = require("node:assert/strict");
const { fixture, POCHEON, SANCHEONG } = require("./test_region_analysis_navigation.cjs");

const f = fixture();
f.api.reconcileAnalysisRegionSelection();
f.api.setAnalysisRegion(SANCHEONG);
f.api.openDictionaryDemand();
assert.match(f.els.demandDashboard.innerHTML, /산청군/);
assert.match(f.els.demandDashboard.innerHTML, /현재 수집자료: 포천글램핑/);
assert.doesNotMatch(f.els.demandDashboard.innerHTML, /99999|own-run/);
assert.equal(f.calls.metrics, 0, "Mismatched run metrics are not even read");
const regionalHistory = structuredClone(f.history.state);
f.api.setActiveTab("demand");
assert.equal(f.api.selectedAnalysisRegion().regionKey, SANCHEONG, "General demand navigation retains the shared region");
assert.equal(f.calls.metrics, 0, "A menu click cannot return to unrelated collection data");
f.api.setActiveTab("demand", { fromHistory: true, analysisRegionSelection: regionalHistory.analysisRegionSelection });
assert.equal(f.calls.metrics, 0);

f.state.data = { run: { keyword: "산청 글램핑" } };
f.api.renderDemand();
assert.match(f.els.demandDashboard.innerHTML, /own-run-demand/);
assert.equal(f.calls.metrics, 1, "A normalized exact region keyword may use its own run");
f.state.data = { run: { keyword: "경남글램핑" } };
f.api.renderDemand();
assert.equal(f.calls.metrics, 1, "Province aggregates cannot represent one selected county");

f.api.setAnalysisRegion("kr_admin_4882000000");
f.state.data = { run: { keyword: "고성글램핑" }, tourismVisitorHistory: { regions: [{ regionKey: "kr_admin_5182000000" }] } };
f.api.renderDemand();
assert.equal(f.calls.metrics, 1, "Same-name counties require matching regional evidence");
f.state.data.tourismVisitorHistory.regions = [];
f.api.renderDemand();
assert.equal(f.calls.metrics, 1, "Ambiguous county name without evidence stays pending");
f.state.data.tourismVisitorHistory.regions = [{ regionKey: "kr_admin_4882000000" }];
f.api.renderDemand();
assert.equal(f.calls.metrics, 2, "One exact official region disambiguates the county name");
f.state.data.tourismVisitorHistory.regions.push({ regionKey: "kr_admin_5182000000" });
f.api.renderDemand();
assert.equal(f.calls.metrics, 2, "Mixed-region data cannot be relabelled as one county");
f.state.data = null;
f.api.setAnalysisRegion(POCHEON);
f.api.openDictionaryDemand();
assert.match(f.els.demandDashboard.innerHTML, /수집결과 없음/);
assert.match(f.els.demandDashboard.innerHTML, /포천시/);
f.api.setAnalysisRegion("");
f.api.openDictionaryDemand();
assert.match(f.els.demandDashboard.innerHTML, /지역을 먼저 선택/);
assert.equal(f.calls.metrics, 2);
console.log("Dictionary demand context: shared selection, exact/mismatched/broad/ambiguous/mixed regions, empty data and history passed");
